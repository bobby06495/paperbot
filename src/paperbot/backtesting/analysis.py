"""Plain-English explanations, research questions and assessments of a run.

Everything here is generated by fixed rules from the run's computed metrics,
validation results and data-quality report: no numbers are invented and no
language model is involved. Each item keeps the computed evidence (numbers from
metrics.json) separate from the interpretation text built from it, and the
reports label the interpretation as automated.
"""


def _money(v) -> str:
    return "N/A" if v is None else f"{'-' if v < 0 else ''}${abs(v):,.2f}"


def _pct(v, d=2) -> str:
    return "N/A" if v is None else f"{v:.{d}f}%"


