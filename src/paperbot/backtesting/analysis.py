def summary(profile, meta: dict, m: dict, periods: dict, quality: dict) -> list[str]:
    """Section A executive summary: short sentences built only from computed values."""
    segs = periods.get("segments", {})
    oos = segs.get("out_of_sample", {})
    tf = profile.time_filter
    checks = ", ".join(b.label or b.type.replace("_", " ") for b in profile.entry)
    lines = [
        f"What it does: {profile.label} ({profile.summary}) trades {profile.timeframe} signals, "
        f"{'flat every day' if profile.holding == 'intraday' else 'holding overnight'}. Entries "
        f"between {tf.earliest_entry_et} and {tf.latest_entry_et} New York time need every check to "
        f"pass ({checks}); the initial stop is {profile.stop.describe()}"
        + (f"; management: {', '.join(b.describe() for b in profile.manage)}" if profile.manage else "")
        + f"; exits: {', '.join(b.describe() for b in profile.exit)}.",
        f"Period tested: {meta.get('period', {}).get('actual_start')} to "
        f"{meta.get('period', {}).get('actual_end')} ({m.get('days', 0)} trading days; requested "
        f"{meta.get('period', {}).get('requested_start')} to {meta.get('period', {}).get('requested_end')}).",
        f"Data: {quality.get('provider')}, {len(quality.get('symbols_with_data', []))} of "
        f"{len(quality.get('symbols_requested', []))} symbols had daily data; "
        f"{quality.get('intraday_days_loaded', 0)} symbol-days of {quality.get('bar', '5m')} bars were used; data status: "
        f"{quality.get('status')}.",
        f"Simulated trades: {m.get('completed_trades', 0)} completed, {m.get('open_positions_end', 0)} "
        "still open at the end.",
        f"Measured result: net P&L {_money(m.get('net_pnl'))} ({_pct(m.get('total_return_pct'))} of "
        f"{_money(m.get('starting_capital'))} starting capital), win rate "
        f"{_pct(m.get('win_rate_pct'), 1)} of completed trades, profit factor "
        f"{m.get('profit_factor') if m.get('profit_factor') is not None else 'N/A'}.",
        f"Largest decline: {_pct(m.get('max_drawdown_pct'))} ({_money(m.get('max_drawdown_usd'))}) from "
        "a previous equity peak.",
        f"Costs: included. Commissions {_money(m.get('total_commission'))}; estimated spread and slippage "
        f"{_money(m.get('total_slippage'))} are built into the fill prices.",
        ("Unseen data: the last part of the period was kept as an out-of-sample check: "
         f"{oos.get('trades', 0)} trades, {_money(oos.get('net_pnl'))}." if oos.get("days")
         else "Unseen data: no out-of-sample segment (period too short)."),
    ]
    if quality.get("synthetic"):
        lines.insert(0, "SYNTHETIC DATA: these figures come from generated prices and say nothing "
                        "about the real strategy.")
    return lines


def assessment(m: dict, periods: dict, quality: dict, stress: dict | None, questions: list[dict],
               cfg: dict) -> dict:
    n = m.get("completed_trades", 0)
    need = cfg["validation"]["min_trades_for_assessment"]
    ci = m.get("mean_trade_ci95")
    shows = [f"Over this period the simulation produced {n} completed trades and a net result of "
             f"{_money(m.get('net_pnl'))} after costs."]
    if ci:
        if ci[0] > 0 or ci[1] < 0:
            shows.append(f"The bootstrap range of the average trade ({_money(ci[0])} to {_money(ci[1])}) "
                         "does not include zero in this sample.")
        else:
            shows.append(f"The bootstrap range of the average trade ({_money(ci[0])} to {_money(ci[1])}) "
                         "includes zero: the average trade could plausibly be zero or negative.")
    concerns = [q for q in questions if q["status"] == "concern"]
    not_established = [
        "That the strategy will be profitable in the future: historical simulation results do not "
        "guarantee future performance.",
        "That live fills would match the simulated fills (no historical bid/ask; fills are modelled).",
        "That the result is statistically significant: no significance test is claimed here.",
    ]
    if n < need:
        not_established.insert(0, f"Anything reliable about the strategy's edge: {n} trades is below "
                                  f"the {need}-trade minimum this project uses.")
    assumptions = [
        f"Quote proxy: ask/bid = last close +/- {cfg['execution']['half_spread_bps']} bps; extra slippage "
        f"{cfg['execution']['slippage_bps']} bps on market-like fills.",
        "Ambiguous bars: when a stop and a profit target could both have been reached in one bar, "
        "the stop is assumed first (conservative).",
        "Timing: an order can fill only in bars that start after it was sent (a pass at 10:05:03 fills "
        "from the 10:10 bar; a force close sent at 15:51 on 5-minute bars sells at the 15:55 open). A "
        "stop raised during a bar applies from the next bar. The bot replaces an unfilled exit at the "
        "next pass, so an exit in practice fills at the next bar's open or not at all (pessimistic for "
        "exits a live order would have filled within its first minutes).",
        f"Buying power: cash x {cfg['execution']['buying_power_multiplier']} (the paper account's "
        "margin may allow more).",
        "Universe: today's index members from the fallback list, so stocks that left the index are "
        "missing (survivorship bias, usually flattering).",
    ]
    data_ok = m.get("days", 0) >= 120 and quality.get("status") != "fail"
    sufficiency = (f"{m.get('days', 0)} trading days and {n} trades. "
                   + ("This is a reasonable length for a first look, but not proof."
                      if data_ok and n >= need else
                      "This is not enough data for a reliable evaluation; treat every figure as illustrative."))
    if stress:
        execution = (f"With {stress.get('multiplier', 3)}x spread and slippage the net result would be "
                     f"{_money(stress.get('net_pnl'))} instead of {_money(m.get('net_pnl'))} "
                     f"(commissions unchanged).")
    else:
        execution = "No execution stress test was run."
    further = [q["next_step"] for q in concerns] or [
        "Repeat on a longer period with the IBKR provider.",
        "Compare simulated fills with paper-trading fills for the same days."]
    return {"computed_findings": shows, "concerns": [q["question"] + " " + q["evidence"] for q in concerns],
            "not_established": not_established, "assumptions": assumptions,
            "data_sufficiency": sufficiency, "costs_and_execution": execution,
            "further_tests": list(dict.fromkeys(further)),
            "label": ("Automated interpretation: generated by fixed rules from the metrics and validation "
                      "results above. It is not investment advice and not a statistical test.")}


